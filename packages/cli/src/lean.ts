/**
 * Lean generation for a project (plan, Sections 5 and 6.6): `simulant lean -p <simulation>`.
 *
 *   <project>/lean/lakefile.toml               created once, then the researcher's
 *   <project>/lean/lean-toolchain              the workspace's toolchain, created once
 *   <project>/lean/Generated/<Module>/Model.lean   replaced by each generation
 *   <project>/lean/Generated/<Module>/revision.json source revision and toolchain of the file
 *   <project>/lean/Proofs/                     hand-written proofs: never written by generation
 *
 * After a change, the proofs must be checked again (`--build` runs `lake build`, which also
 * checks them, after a scan for constructs a proof file may not use).
 */
import { spawn } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { ProjectType } from '@bramas/simulant-core/types/project';
import type { Experiment } from '@bramas/simulant-lang/ir';
import { checkProofFile } from '@bramas/simulant-lean-gen/check-proofs';
import { generateModel } from '@bramas/simulant-lean-gen/model';
import { leanModuleName } from '@bramas/simulant-lean-gen/names';
import type { Print } from './explorer-commands';

const workspaceLean = fileURLToPath(new URL('../../../lean/', import.meta.url));

export { leanModuleName } from '@bramas/simulant-lean-gen/names';

function writeIfChanged(file: string, text: string): boolean {
  if (existsSync(file) && readFileSync(file, 'utf8') === text) return false;
  writeFileSync(file, text);
  return true;
}

/** Writes the generated files; returns the paths written. Never touches `Proofs/`. */
export function generateProjectLean(project: ProjectType<any, any>, simulation: string, projectDir: string, out = join(projectDir, 'lean')) {
  if (!project.experiment) throw new Error(`${simulation} is not a .sim project: there is nothing to generate`);
  const module = leanModuleName(simulation);
  const exp = project.experiment().ir as Experiment;
  const written: string[] = [];
  mkdirSync(join(out, 'Generated', module), { recursive: true });
  mkdirSync(join(out, 'Proofs'), { recursive: true });
  const lakefile = join(out, 'lakefile.toml');
  if (!existsSync(lakefile)) {
    writeFileSync(lakefile, `name = "${leanModuleName(projectDir.split('/').pop() ?? 'project')}"
defaultTargets = ["Generated", "Proofs"]

# The Simulant semantic core and component library.
[[require]]
name = "simulant"
path = "${relative(out, workspaceLean) || '.'}"

# Generated by \`simulant lean\`: replaced by each generation.
[[lean_lib]]
name = "Generated"
globs = ["Generated.+"]

# Hand-written proofs: never written by generation.
[[lean_lib]]
name = "Proofs"
globs = ["Proofs.+"]
`);
    written.push(lakefile);
  }
  const toolchain = join(out, 'lean-toolchain');
  if (!existsSync(toolchain)) {
    writeFileSync(toolchain, readFileSync(join(workspaceLean, 'lean-toolchain'), 'utf8'));
    written.push(toolchain);
  }
  const model = join(out, 'Generated', module, 'Model.lean');
  if (writeIfChanged(model, generateModel(exp, `Generated.${module}`))) written.push(model);
  const revision = join(out, 'Generated', module, 'revision.json');
  const info = { simulation, experiment: exp.name, revision: project.revision?.(), toolchain: readFileSync(join(workspaceLean, 'lean-toolchain'), 'utf8').trim() };
  if (writeIfChanged(revision, JSON.stringify(info, null, 2) + '\n')) written.push(revision);
  return { module, out, written };
}

/** Problems of the hand-written proof files (forbidden constructs, see check-proofs.ts). */
export function scanProofs(out: string): string[] {
  const dir = join(out, 'Proofs');
  const files = existsSync(dir) ? readdirSync(dir, { recursive: true }).map(String).filter(f => f.endsWith('.lean')) : [];
  return files.flatMap(f => checkProofFile(readFileSync(join(dir, f), 'utf8')).map(p => `Proofs/${f}: ${p}`));
}

/** `lake build` in the project's Lean directory; cancelled by `signal`. */
export function lakeBuild(out: string, print: Print, signal?: AbortSignal): Promise<number> {
  return new Promise(resolve => {
    const child = spawn('lake', ['build'], { cwd: out, signal });
    let output = '';
    child.stdout.on('data', d => { output += d; });
    child.stderr.on('data', d => { output += d; });
    child.on('error', error => {
      if (!signal?.aborted) print(`lake build failed to start: ${error.message}`);
      resolve(1);
    });
    child.on('close', code => {
      if (signal?.aborted) return resolve(1);
      if (code) print(output.trim());
      resolve(code ? 1 : 0);
    });
  });
}

export async function leanCommand(
  project: ProjectType<any, any>, simulation: string, projectDir: string,
  options: { out?: string; build?: boolean; signal?: AbortSignal }, print: Print,
): Promise<number> {
  const { module, out, written } = generateProjectLean(project, simulation, projectDir, options.out);
  print(`Lean model of ${simulation}: ${join(out, 'Generated', module, 'Model.lean')} (revision ${project.revision?.() ?? '?'})`);
  print(written.length ? `Written: ${written.map(f => relative(out, f)).join(', ')}` : 'Up to date: nothing written.');
  if (written.some(f => f.endsWith('Model.lean'))) print('The proofs in Proofs/ must be checked again against the new definitions.');
  const problems = scanProofs(out);
  for (const p of problems) print(`❌ ${p}`);
  if (problems.length) return 1;
  if (!options.build) return 0;
  print('Running lake build (the generated model and the proofs)...');
  const code = await lakeBuild(out, print, options.signal);
  if (!options.signal?.aborted) print(code ? '❌ lake build failed' : '✅ lake build succeeded: the model and the proofs check');
  return code;
}
