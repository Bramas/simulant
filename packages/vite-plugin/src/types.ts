/**
 * TypeScript types of an experiment's snapshots (plan, Section 6.5), for
 * editor completion in drawing code: `snapshot.world.site`, `agent.pub.bh`.
 * Written to `.simulant/types/<experiment>.d.ts`; read-only.
 */
import { layout } from '@bramas/simulant-lang/layout';
import type { Experiment, Type } from '@bramas/simulant-lang/ir';
import { resolvePub } from '@bramas/simulant-lang/types';

function ts(t: Type, pub: Type): string {
  switch (t.k) {
    case 'unit': return 'null';
    case 'bool': case 'frame': return 'boolean';
    case 'nat': case 'int': case 'node': case 'agent': return 'number';
    case 'string': return 'string';
    case 'move': return 'Move';
    case 'verdict': return `'success' | 'failure' | 'inProgress'`;
    case 'enum': return t.ctors.map(c => `'${c}'`).join(' | ') || 'never';
    case 'pub': return ts(pub, pub);
    case 'option': return `${ts(t.of, pub)} | null`;
    case 'list': case 'multiset': return `readonly (${ts(t.of, pub)})[]`;
    case 'record': return `{ ${t.fields.map(f => `readonly ${f.name}: ${ts(resolvePub(f.type, pub), pub)};`).join(' ')} }`;
    default: return 'unknown';
  }
}

export function snapshotTypes(exp: Experiment): string {
  const lay = layout(exp);
  const pub = lay.pub;
  const record = (fields: { name: string; type: Type }[]) => `{ ${fields.map(f => `readonly ${f.name}: ${ts(f.type, pub)};`).join(' ')} }`;
  return `/* Generated by Simulant from experiment \`${exp.name}\`. Do not edit: it is regenerated on compilation. */
import type { Snapshot as BaseSnapshot, SnapshotAgent as BaseAgent } from '@bramas/simulant-ui/sim/snapshot';
export type { Layout, ModelInfo, RenderOptions } from '@bramas/simulant-ui/sim/types';

export type Move = 'stay' | 'cw' | 'ccw';
/** Public state of the algorithm \`${exp.algorithm.name}\`. */
export type Pub = ${ts(pub, pub)};
/** Memory of the algorithm (private: no agent sees it). */
export type Mem = ${ts(lay.mem, pub)};
/** World fields of the components (${exp.model.components.map(c => c.name).join(', ') || 'none'}). */
export type World = ${record(lay.world)};
/** Flags raised on agents. */
export type Flags = ${record(lay.flags.map(f => ({ name: f.name, type: { k: 'bool' } as Type })))};
/** Agent fields of the components. */
export type Fields = ${record(lay.agentFields)};
export type Agent = Omit<BaseAgent, 'pub' | 'mem' | 'flags' | 'fields'> & {
  readonly pub: Pub; readonly mem: Mem; readonly flags: Flags; readonly fields: Fields;
};
export type Snapshot = Omit<BaseSnapshot, 'agents' | 'world'> & { readonly agents: readonly Agent[]; readonly world: World };
`;
}
